
public class OperatorTest2 {
	public static void main(String[] args) {
		System.out.println(3<<1); // 3 → 6(3*2¹)
		System.out.println(3<<2); // 3 → 12(3*2²)
		System.out.println(3<<3); // 3 → 24(3*2³)
		
		System.out.println(8>>1); // 8 → 4(8/2¹)
		System.out.println(8>>2); // 8 → 2(8/2²)
		System.out.println(8>>3); // 8 → 1(8/2³)
	}
}